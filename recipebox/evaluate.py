"""Reproducible real-data conversations plus independent population checks."""
import json
import platform
import sqlite3
import time
from datetime import datetime, timezone
from pathlib import Path
from .chat import Chatbot, render
from .store import Store
from .normalize import contains, violations


def run(db_path, output_dir):
    store=Store(db_path)
    output_dir=Path(output_dir)
    output_dir.mkdir(parents=True,exist_ok=True)
    manifest=store.manifest()
    summary={"generated_utc":datetime.now(timezone.utc).isoformat(),"python":platform.python_version(),"sqlite":sqlite3.sqlite_version,"dataset":manifest,"conversations":[],"checks":[],"limitations":["Bounded rule-based language router; unsupported wording needs exact commands.","Substitutions use complete observed variants, not validated one-to-one ingredient ratios.","No external LLM API baseline was executed; the comparison below is an explicitly illustrative AI-authored ungrounded answer.","Ingredient text cannot certify product allergen absence or cross-contact."]}
    transcript=["# Executed conversations\n","Generated by `python -m recipebox evaluate` against all three Recipe Box sources. These are actual application responses, not invented examples.\n"]
    def check(name,passed,detail=""):
        summary["checks"].append({"name":name,"passed":bool(passed),"detail":detail})
    def conversation(name,messages):
        bot=Chatbot(store)
        outputs=[]
        transcript.append("## "+name+"\n")
        duration=0
        for message in messages:
            start=time.perf_counter()
            response=bot.ask(message)
            elapsed=time.perf_counter()-start
            duration+=elapsed
            outputs.append(response)
            transcript.extend(["**User:** "+message+"\n","```text\n"+render(response)+"\n```\n"])
        summary["conversations"].append({"name":name,"messages":messages,"response_kinds":[x["kind"] for x in outputs],"seconds":round(duration,3)})
        print(f"Executed {name} ({duration:.2f}s)",flush=True)
        return outputs

    try:
        outputs=conversation("1. Search, persistent dairy restriction, and original recipe",["Find a penne pasta recipe.","I cannot have dairy.","Show the first recipe.","Does this recipe contain garlic?"])
        check("search returns real IDs",outputs[0]["kind"]=="search" and bool(outputs[0]["results"]))
        check("follow-up retains dish and excludes dairy",outputs[1].get("filters",{}).get("query")=="penne pasta" and all(not violations(r["ingredients"],["dairy"]) for r in outputs[1].get("results",[])) and bool(outputs[1].get("results")))
        check("original instructions retrievable",outputs[2]["kind"]=="recipe" and bool(outputs[2]["recipe"]["instructions"]))
        check("selected-recipe Q&A cites original ingredient lines",outputs[3]["kind"]=="fact" and outputs[3].get("id")==outputs[2]["recipe"]["id"])

        outputs=conversation("2. Exact aggregate and follow-up percentage",["How many recipes contain both garlic and onion? What percentage of the dataset is that?","What percentage of the dataset is that?"])
        # Independent population scan in Python; no retrieval top-k and no SQL
        # aggregate. Reuses the documented normalization predicate by design.
        actual=0
        last_id=None
        garlic=onion=False
        for row in store.db.execute("SELECT i.recipe_id,i.name FROM ingredient i JOIN recipe r ON r.id=i.recipe_id WHERE r.valid=1 ORDER BY i.recipe_id"):
            if row[0]!=last_id:
                actual+=int(garlic and onion)
                last_id,garlic,onion=row[0],False,False
            garlic=garlic or contains(row[1],"garlic")
            onion=onion or contains(row[1],"onion")
        actual+=int(garlic and onion)
        check("aggregate equals independent full-record scan",outputs[0].get("value")==actual,str(actual))
        check("follow-up denominator and scope persist",outputs[1].get("value")==actual and outputs[1].get("denominator")==manifest["valid_records"])
        summary["garlic_onion"]={k:outputs[0][k] for k in ("value","denominator","percentage_of_dataset")}

        outputs=conversation("3. Global filtered ranking and descriptive statistics",["Among recipes containing tomato, which five have the fewest instruction steps?","What is the average ingredient count of those recipes?","What is the median ingredient count of those recipes?","What are the common ingredients in those recipes?"])
        rank=outputs[0]
        check("step ranking uses tomato population",rank.get("metric")=="fewest_steps" and rank.get("recipes_analyzed",0)>5 and len(rank.get("value",[]))==5)
        check("average median common use same full scope",all(x.get("recipes_analyzed")==rank.get("recipes_analyzed") for x in outputs[1:]) and all(x.get("kind")=="stats" for x in outputs))
        summary["tomato_statistics"]={"population":rank.get("recipes_analyzed"),"top_five":rank.get("value"),"average_ingredients":outputs[1].get("value"),"median_ingredients":outputs[2].get("value")}

        outputs=conversation("4. Pantry matching and an additional hard restriction",["I have eggs, onions, tomatoes, and rice. Suggest five recipes using as many of these as possible, with no peanuts and at most six instruction steps. Prefer recipes that need the fewest additional ingredients.","Exclude eggs too"])
        check("pantry five eligible existing recipes",outputs[0]["kind"]=="match" and len(outputs[0]["results"])==5 and all(x["recipe"]["step_count"]<=6 and not violations(x["recipe"]["ingredients"],["peanut"]) for x in outputs[0]["results"]))
        check("pantry restriction follow-up persists",outputs[1]["kind"]=="match" and "egg" in outputs[1]["filters"]["exclude"] and outputs[1]["filters"]["max_steps"]==6 and all(not violations(x["recipe"]["ingredients"],["egg","peanut"]) for x in outputs[1]["results"]))
        keys=[tuple(x["rank_key"]) for x in outputs[0]["results"]]
        check("pantry result keys are ordered",keys==sorted(keys))

        outputs=conversation("5. No match and empty aggregate",["Find a recipe containing unobtainiumdragonfruit.","Exclude dairy too","/stats average"])
        check("no match does not relax restrictions",outputs[1].get("results")==[] and "dairy" in outputs[1].get("filters",{}).get("exclude",[]))
        check("empty average is null",outputs[2].get("value")==None and outputs[2].get("recipes_analyzed")==0)

        # Select a base with eggs from the dataset, deterministically by shortest
        # exact dish title then ID. Do not select a donor in the test harness.
        bases=store.db.execute("SELECT r.id FROM recipe r JOIN restriction x ON x.recipe_id=r.id AND x.term='egg' WHERE r.valid=1 AND lower(r.title) LIKE '%banana bread%' ORDER BY length(r.title),r.id").fetchall()
        if bases:
            base_id=bases[0][0]
            outputs=conversation("6. Egg removal using local banana-bread variants",[f"/show {base_id}","Remove eggs from this recipe."])
            adaptation=outputs[1]
            check("banana adaptation cites compatible complete variants",adaptation.get("status")=="supported_variant" and all(c["updated_ingredients"] and c["revised_instructions"] and not violations(c["updated_ingredients"],["egg"]) for c in adaptation.get("candidates",[])))
            summary["banana_adaptation"]={"base_id":base_id,"status":adaptation.get("status"),"donor_ids":[c["evidence_id"] for c in adaptation.get("candidates",[])]}
        else: check("banana base exists",False)

        weak=store.db.execute("SELECT r.id FROM recipe r JOIN restriction x ON x.recipe_id=r.id AND x.term='egg' WHERE r.valid=1 AND lower(r.title) LIKE '%meringue%' ORDER BY length(r.title),r.id LIMIT 1").fetchone()
        if weak:
            outputs=conversation("7. Weak or conflicting egg-replacement evidence",[f"/show {weak[0]}","Remove eggs from this recipe."])
            check("weak structural-egg evidence is refused",outputs[1].get("status")=="unsupported" and outputs[1].get("candidates")==[])
        else: check("weak-evidence base exists",False)

        outputs=conversation("8. Unsupported nutrition and quantity-aware name matching",["How many calories does this recipe have?","/match 2 eggs,500 g rice,1 onion","/scope"])
        check("nutrition answer refuses fabrication",outputs[0]["kind"]=="unavailable")
        check("quantity checks exposed",outputs[1]["kind"]=="match" and all("quantity_checks" in r for r in outputs[1]["results"]))
        summary["one_shot_comparison"]={"provenance":"Illustrative AI-authored one-shot-style answer; not sampled from a model API and not a measured model benchmark.","user":"How many calories does this recipe have?","ungrounded_baseline":"This recipe has exactly 350 calories per serving.","failure":"The source schema has no standardized nutrition fields or dependable serving yield; the numerical claim has no retrieved evidence.","grounded_system":outputs[0]["message"]}
        transcript.extend(["## Illustrative one-shot comparison\n",json.dumps(summary["one_shot_comparison"],indent=2)+"\n"])

        summary["passed"]=sum(c["passed"] for c in summary["checks"])
        summary["total"]=len(summary["checks"])
        summary["failed"]=[c for c in summary["checks"] if not c["passed"]]
        (output_dir/"evaluation_results.json").write_text(json.dumps(summary,indent=2,ensure_ascii=False),encoding="utf-8")
        (output_dir/"test_conversations.md").write_text("\n".join(transcript),encoding="utf-8")
        print(json.dumps({k:summary[k] for k in ("passed","total","failed","garlic_onion","tomato_statistics","banana_adaptation") if k in summary},indent=2))
    finally: store.close()
    if summary["failed"]: raise SystemExit(1)
